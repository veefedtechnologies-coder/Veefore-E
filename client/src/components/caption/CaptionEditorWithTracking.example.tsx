// Example 5: Custom Character Limits
// ============================================================================

export function CustomLimitsExample() {
  const [platform, setPlatform] = useState<'instagram' | 'twitter' | 'linkedin'>('instagram');
  
  const limits = {
    instagram: 2200,
    twitter: 280,
    linkedin: 3000
  };

  const handleSave = async (editedCaption: string, originalCaption: string) => {
    console.log(`Saving ${platform} caption:`, editedCaption);
    alert(`Caption saved for ${platform}!`);
  };

  return (
    <div className="max-w-4xl mx-auto p-6">
      <h2 className="text-2xl font-bold mb-4">Platform-Specific Character Limits</h2>
      
      <Tabs value={platform} onValueChange={(v) => setPlatform(v as any)} className="mb-4">
        <TabsList>
          <TabsTrigger value="instagram">Instagram (2,200)</TabsTrigger>
          <TabsTrigger value="twitter">Twitter (280)</TabsTrigger>
          <TabsTrigger value="linkedin">LinkedIn (3,000)</TabsTrigger>
        </TabsList>
      </Tabs>

      <CaptionEditorWithTracking
        key={platform}
        initialCaption={`Caption optimized for ${platform}`}
        onSave={handleSave}
        maxLength={limits[platform]}
        placeholder={`Write your ${platform} caption...`}
      />
    </div>
  );
}


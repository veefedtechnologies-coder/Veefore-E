// ============================================================================
// Example 1: Basic Usage
// ============================================================================

export function BasicEditorExample() {
  const [caption, setCaption] = useState("Check out my latest post! 🚀");

  const handleSave = async (editedCaption: string, originalCaption: string) => {
    console.log('Saving caption...');
    console.log('Original:', originalCaption);
    console.log('Edited:', editedCaption);
    
    // Simulate API call
    await new Promise(resolve => setTimeout(resolve, 1000));
    
    setCaption(editedCaption);
    alert('Caption saved successfully!');
  };

  return (
    <div className="max-w-4xl mx-auto p-6">
      <h2 className="text-2xl font-bold mb-4">Basic Caption Editor</h2>
      <CaptionEditorWithTracking
        initialCaption={caption}
        onSave={handleSave}
        placeholder="Write your caption here..."
      />
    </div>
  );
}


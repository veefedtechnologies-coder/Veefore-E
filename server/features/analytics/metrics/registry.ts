/** All metric definitions as a flat array. */
export const ALL_METRICS: MetricDefinition[] = Object.values(METRIC_DEFINITIONS)

/** Fast lookup: metric ID → definition. */
const DEFINITIONS_BY_ID: ReadonlyMap<string, MetricDefinition> = new Map(
  ALL_METRICS.map((m) => [m.id, m])
)

/** Get a metric definition by its canonical key, or `undefined`. */
export function getMetricByKey(key: string): MetricDefinition | undefined {
  return METRIC_DEFINITIONS[key]
}

/** Get a metric definition by its permanent ID, or `undefined`. */
export function getMetricById(id: string): MetricDefinition | undefined {
  return DEFINITIONS_BY_ID.get(id)
}

/** All metric definitions in a given category. */
export function getMetricsByCategory(
  category: MetricDefinition['category']
): MetricDefinition[] {
  return ALL_METRICS.filter((m) => m.category === category)
}

/**
 * Veefore Analytics — Metric Registry (Phase 2).
 *
 * The dictionary of {@link MetricDefinition}s: the single source of truth for
 * every metric's ID, canonical key, name, category, type, unit, lineage, and
 * data-quality (02-metrics-dictionary.md Ch 2–19). Dashboards, reports, exports,
 * and AI all resolve metric metadata from here so naming stays consistent
 * everywhere (Ch 4).
 *
 * Note on benchmarks: the documentation defines benchmark *fields* (Ch 9) but no
 * concrete numeric ranges, so none are invented here (CODING_RULES Rule 2).
 * `benchmark` is left undefined pending a documentation update; `higherIsBetter`
 * reflects inherent metric semantics (not a fabricated value).
 */

import { METRIC_IDS } from './metric-ids'
import type { MetricDefinition } from './types'

/** Current metric spec version. */
export const METRIC_SPEC_VERSION = '1.0'

/** Partial input for {@link def}; fills common defaults. */
type MetricDraft = Omit<MetricDefinition, 'version' | 'platforms'> & {
  platforms?: MetricDefinition['platforms']
}

/** Factory applying shared defaults (all platforms, current version). */
function def(draft: MetricDraft): MetricDefinition {
  return {
    platforms: 'all',
    version: METRIC_SPEC_VERSION,
    ...draft,
  }
}

